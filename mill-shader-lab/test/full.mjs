import assert from "node:assert/strict";
import { labPage, watchErrors, withLab } from "./browser.mjs";
import { pixelStats, samePixels } from "./pixels.mjs";
import { waterline } from "./waterline.mjs";

await withLab(async ({ base, context }) => {
  const desktop = await context();
  const page = await desktop.newPage();
  const assertClean = watchErrors(page);
  await page.addInitScript(() => {
    const play = HTMLMediaElement.prototype.play;
    window.millAudio = new Set();
    HTMLMediaElement.prototype.play = async function () {
      await play.call(this);
      window.millAudio.add(this);
    };
  });
  await page.goto(base.href);
  const ui = labPage(page);
  const { $, choose, check, click, control: set, open, ready, reveal, side, shot, view } = ui;
  await ready();
  assert.match(await $("status").textContent(), /Original mill · WebGL 2 · Float targets available/);
  await waterline(ui);
  const pixels = (a, b) => pixelStats(page, a, b);
  const compare = async (a, b, label, minimum = 120) => {
    const diff = await pixels(a, b);
    assert.ok(diff.count > minimum, `${label}: ${JSON.stringify(diff)}`);
    return diff;
  };
  const pair = async (id, setup) => {
    await open(id);
    if (setup) await setup();
    await side("a"); const a = await shot();
    const time = await $("clock").textContent();
    await side("b"); const b = await shot();
    assert.equal(await $("clock").textContent(), time, id + " clock");
    await compare(a, b, id);
  };

  await open("spaces");
  const keyboard = await shot();
  await $("scene").focus();
  await page.keyboard.press("Enter");
  assert.match(await $("point").textContent(), /Object .*World .*View .*Screen UV/);
  await page.keyboard.press("ArrowRight");
  await compare(keyboard, await shot(), "keyboard orbit", 10000);
  await page.keyboard.press("Shift+ArrowUp");
  await page.keyboard.press("+");
  await page.keyboard.press("Tab");
  assert.equal(await page.locator(":focus").getAttribute("id"), "play");
  const norms = await view("Encoded normals");
  const raw = await view("Raw depth");
  const linear = await view("Linear depth");
  const position = await view("View position");
  await compare(norms, raw, "normal / depth");
  await compare(raw, linear, "raw / linear depth");
  await compare(linear, position, "linear depth / view position");
  await page.locator("#shader-code summary").click();
  await page.waitForFunction(() => document.querySelector("#code").textContent.length > 0);
  assert.match(await $("code").textContent(), /layout\(location = 0\)/);
  await choose("shader-stage", "vertex");
  assert.match(await $("code").textContent(), /modelViewMatrix/);
  await page.locator("#shader-code summary").click();

  await pair("material");
  const mapped = await shot();
  await choose("texture", 0);
  await compare(mapped, await shot(), "UV checker");
  await choose("texture", 1);
  const mappedDepth = await view("Raw depth");
  await choose("normals", 2);
  await samePixels(page, mappedDepth, await shot(), "Normal perturbation leaves geometry depth unchanged");
  await compare(mapped, await view("Final color"), "procedural normals");
  await pair("lighting");
  const spec = await view("Specular");
  const shadows = await view("Shadow visibility");
  assert.ok((await pixels(spec)).max > 20);
  assert.ok((await pixels(shadows)).max > 225);
  await check("shadows", false);
  await compare(shadows, await shot(), "Shadow visibility with and without casters");
  await check("shadows", true);
  await view("Final color");
  await choose("lighting", 1);
  const phong = await shot();
  await choose("lighting", 2);
  await compare(phong, await shot(), "Phong / Blinn–Phong", 25);
  await pair("ggx");
  const rough = await shot();
  await set("roughness", 0.82);
  await compare(rough, await shot(), "GGX roughness");
  await set("metalness", 1);
  await compare(rough, await shot(), "GGX metalness");
  await pair("stylized", () => check("fresnel", true));
  await check("fresnel", false); await check("rim", true);
  await side("a"); const plain = await shot();
  await side("b"); await compare(plain, await shot(), "rim");
  await check("rim", false); await check("cel", true);
  await compare(plain, await shot(), "cel bands");

  await open("deferred");
  await side("a"); const forward = await shot();
  await side("b"); const deferred = await shot();
  const matched = await pixels(forward, deferred);
  assert.ok(matched.mean < 3.5, `Forward/deferred should agree: ${JSON.stringify(matched)}`);
  await view("Deferred color");
  await page.locator("#shader-code summary").click();
  await choose("shader-stage", "fragment");
  assert.match(await $("code").textContent(), /texture\(albedoTexture, screenUV\)/);
  await page.locator("#shader-code summary").click();
  console.log(`Forward/deferred: mean RGB error ${matched.mean.toFixed(3)} / 255`);

  await pair("reflection");
  const reflUV = await view("Reflection hit UV");
  const reflection = await pixels(reflUV);
  assert.ok(reflection.hits > 600 && reflection.misses > 1000, JSON.stringify(reflection));
  await $("scene").press("ArrowRight");
  await $("scene").press("ArrowRight");
  await compare(reflUV, await shot(), "reflection changes when orbiting");
  await click("Restore pond view");
  await view("Reflection color");
  await click("Aim down at water");
  const croppedReflection = await view("Reflection hit UV");
  const cropped = await pixels(croppedReflection);
  assert.ok(cropped.misses > reflection.misses && cropped.hits < reflection.hits, JSON.stringify({ cropped, reflection }));

  await pair("foam", () => set("foamDepth", 3));
  const band = await view("Foam");
  await side("a");
  const thin = await shot();
  assert.ok((await pixels(band)).colored > (await pixels(thin)).colored + 250);
  const flow = await view("Flow UV");
  await $("step").click();
  await compare(flow, await shot(), "advected UV");
  await view("Flow direction");

  await pair("fog");
  const fog = await view("Fog amount");
  assert.ok((await pixels(fog)).max > 60);
  await pair("smoke");
  assert.equal(await $("stage-title").textContent(), "Chimney");
  const volumeMask = await view("Smoke mask");
  await side("a");
  const spriteMask = await shot();
  assert.ok((await pixels(spriteMask)).max > 60 && (await pixels(volumeMask)).max > 60, "Both sides draw a plume");
  await compare(spriteMask, volumeMask, "Sprite vs. volume opacity");
  await choose("smoke", 1);
  await samePixels(page, spriteMask, await shot(), "Both sides agree when they use sprites at the same frame");
  await choose("smoke", 0);
  assert.equal((await pixels(await shot())).max, 0, "Turning smoke off clears the mask");
  await choose("smoke", 2);
  await $("step").click();
  await compare(volumeMask, await shot(), "Stepped volume");
  await side("a");
  await compare(spriteMask, await shot(), "Stepped sprites");
  await $("reset").click();
  await samePixels(page, volumeMask, await view("Smoke mask"), "Reset restores the initial volume and frame");

  await pair("ssao");
  const ao = await view("SSAO raw");
  const filtered = await view("SSAO filtered");
  assert.ok((await pixels(ao)).min < 175);
  await compare(ao, filtered, "AO filtering");
  await set("aoRadius", 1.7);
  await compare(filtered, await shot(), "AO radius");
  await choose("bookmark", "Waterline"); await shot();
  await pair("outline");
  await view("Outline edges");
  await pair("focus", () => click("Focus dock"));
  assert.match(await $("point").textContent(), /Screen UV/);
  const dock = await view("Focus / blur mask");
  await click("Focus mill");
  assert.match(await $("point").textContent(), /Screen UV/);
  await compare(dock, await shot(), "focus distance", 10000);
  const blurred = await view("Blurred source");
  await compare(blurred, await view("Dilated blur"), "dilation source");
  await pair("motion", () => click("Hold sweep frame"));
  const motion = await view("Motion direction");
  await click("Stopped camera");
  const stoppedDirection = await shot();
  await compare(motion, stoppedDirection, "motion / stopped direction");
  await view("Final color");
  await side("a"); const stillA = await shot();
  await side("b"); await samePixels(page, stillA, await shot(), "Stationary camera produces no motion blur");

  await pair("filter");
  await choose("filter", 2); const gaussian = await shot();
  await choose("filter", 3); await compare(gaussian, await shot(), "Kuwahara / Gaussian");
  await pair("bloom");
  const bright = await view("Bloom extraction");
  const glow = await view("Bloom blur");
  const brightStats = await pixels(bright);
  assert.ok(brightStats.colored > 150 && brightStats.colored < 50000, JSON.stringify(brightStats));
  await compare(bright, glow, "HDR spread");
  await view("Bloom combined");
  await pair("sampling", () => check("poster", true));
  const brightnessBands = await shot();
  await choose("posterStyle", 1);
  await compare(brightnessBands, await shot(), "brightness / channel quantization");
  await check("poster", false);
  const noSample = await shot();
  await check("pixel", true);
  const pixel = await shot();
  await compare(noSample, pixel, "pixelize");
  await check("pixelBackground", false);
  await compare(pixel, await shot(), "pixelize background mask", 20);
  await check("pixel", false); await check("sharpen", true);
  await compare(noSample, await shot(), "sharpen");
  await pair("grain");
  const beforeGrain = await shot();
  await $("step").click();
  await compare(beforeGrain, await shot(), "stepped grain");
  const grainHeld = await shot();
  await click("Focus mill");
  await compare(grainHeld, await shot(), "focused chromatic aberration");
  await pair("grade");
  await choose("grade", 3); const night = await shot();
  await choose("grade", 5); await compare(night, await shot(), "split tone");
  await check("grayRamp", true);
  await choose("grade", 0);
  const exact = await shot();
  await choose("encoding", 1); await compare(exact, await shot(), "encoding curves", 10000);

  await reveal("scene-effects");
  await click("Load Legacy preset");
  const day = await shot();
  await click("Midnight");
  await compare(day, await shot(), "Legacy midday / midnight", 10000);
  const smoke = await view("Smoke mask");
  assert.ok((await pixels(smoke)).colored > 30);
  assert.equal(await page.evaluate(() => window.millAudio.size), 0, "Sound starts only on opt-in");
  await check("sound", true);
  await page.waitForFunction(() => window.millAudio.size === 2 && [...window.millAudio].every(audio => !audio.paused));
  assert.equal(await $("audio-status").textContent(), "");
  await check("sound", false);
  assert.ok(await page.evaluate(() => [...window.millAudio].every(audio => audio.paused)));
  assertClean();

  await page.close();
  await fallbacks(desktop, base);
  const touch = await context({
    viewport: { width: 360, height: 740 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1,
  });
  const narrow = await touch.newPage();
  const assertTouchClean = watchErrors(narrow);
  await narrow.goto(base.href);
  const touchUI = labPage(narrow);
  const touchScene = narrow.locator("#scene");
  await touchUI.ready();
  assert.equal(await narrow.evaluate(() => document.documentElement.scrollWidth), 360);
  const bounds = await touchScene.boundingBox();
  assert.ok(bounds);
  const start = { x: Math.round(bounds.x + bounds.width * 0.52), y: Math.round(bounds.y + bounds.height * 0.5) };
  const original = await touchUI.shot();
  const client = await touch.newCDPSession(narrow);
  await client.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [start] });
  await client.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: start.x + 52, y: start.y + 15 }] });
  await client.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  const dragged = await touchUI.shot();
  assert.ok((await pixelStats(narrow, original, dragged)).count > 1000, "Touch drag must move the scene");
  await narrow.locator("#overview").tap();
  assert.equal(await narrow.locator("#stage-title").textContent(), "Overview");
  await narrow.locator("#side-a").tap();
  assert.equal(await narrow.locator("#side-a").getAttribute("aria-pressed"), "true");
  await narrow.locator("#reset").tap();
  assert.equal(await narrow.locator("#stage-title").textContent(), "Waterline");
  assertTouchClean();
  console.log("All 20 live lessons, audio, capability and asset recovery, keyboard and 360 px touch passed");
});

async function fallbacks(context, base) {
  const sdr = await context.newPage();
  const assertClean = watchErrors(sdr);
  await sdr.addInitScript(() => {
    const getExtension = WebGL2RenderingContext.prototype.getExtension;
    WebGL2RenderingContext.prototype.getExtension = function (name) {
      return name === "EXT_color_buffer_float" ? null : getExtension.call(this, name);
    };
  });
  await sdr.goto(base.href);
  const ui = labPage(sdr);
  await ui.ready();
  await ui.open("bloom");
  assert.match(await ui.$("status").textContent(), /SDR targets/);
  assert.equal(await ui.$("bloom").locator('option[value="2"]').evaluate(option => option.disabled), true);
  assert.equal(await ui.$("bloom").inputValue(), "1");
  const legacy = await ui.shot();
  await ui.choose("bloom", "0");
  assert.ok((await pixelStats(sdr, legacy, await ui.shot())).count > 120, "SDR legacy bloom must render");
  await ui.open("smoke");
  assert.ok((await pixelStats(sdr, await ui.view("Smoke mask"))).max > 60, "SDR smoke volume must render");
  assertClean();
  await sdr.close();

  const none = await context.newPage();
  await none.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (type, ...args) {
      return type === "webgl2" ? null : getContext.call(this, type, ...args);
    };
  });
  await none.goto(base.href);
  await none.locator("#fallback:visible").waitFor();
  assert.match(await none.locator("#failure").textContent(), /WebGL 2/);
  assert.equal(await none.locator("#scene").isVisible(), false);
  await none.close();

  const missing = await context.newPage();
  await missing.route(new URL("mill-assets/scene.json", base).href,
    route => route.fulfill({ status: 404 }), { times: 1 });
  await missing.goto(base.href);
  await missing.locator("#fallback:visible").waitFor();
  assert.match(await missing.locator("#failure").textContent(), /scene\.json returned HTTP 404/);
  await missing.locator("#retry").click();
  await labPage(missing).ready();
  await missing.close();
}
